// Запуск: jsc -m tests/receipt.test.js  (или node tests/receipt.test.js)
import { parseReceipt } from '../js/lib/receipt-parse.js';

const out = typeof print === 'function' ? print : (...a) => console.log(...a);
let passed = 0;
let failed = 0;

function eq(actual, expected, name) {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) passed++;
  else {
    failed++;
    out(`✗ ${name}\n    ожидали: ${e}\n    получили: ${a}`);
  }
}

const items = (text) => parseReceipt(text).items.map((it) => [it.name, it.amount]);

// Типичный чек: шапка, товары, скидка под товаром, итог, оплата
const receipt = `ООО "Евроторг" УНП 101168731
Магазин №123 г. Минск
Кассир Иванова
Чек № 4567  20.11.2026 12:38
Молоко 3,2% 1л
1 x 2,89   2,89
Скидка        -0,50
Хлеб Нарочанский
1.000 x 1,79   1,79
Бананы
1.234 x 3,49
Картофель 2,10
ИТОГО: 11,59
Карта            11,59
НДС 20%           1,93
Спасибо за покупку!`;
const r = parseReceipt(receipt);
eq(items(receipt), [['Молоко 3,2% 1л', 239], ['Хлеб Нарочанский', 179], ['Бананы', 431], ['Картофель', 210]],
  'чек: товары по строкам, скидка вычтена из товара выше, весовой товар перемножен, служебные строки пропущены');
eq(r.total, 1159, 'итог из строки ИТОГО');
eq(r.warnings.length, 1, 'сумма товаров 10,59 ≠ итог 11,59 — предупреждение');
eq(r.warnings[0].includes('разница 1,00'), true, 'в предупреждении указана разница');

// Итог сходится — предупреждений нет
const ok = `Сыр Гауда 1 x 7,45 7,45
Скидка по карте 0,45
Кефир 1,99
ИТОГО 8,99`;
eq(items(ok), [['Сыр Гауда', 700], ['Кефир', 199]], 'скидка без минуса в той же строке');
eq(parseReceipt(ok).warnings, [], 'итог сходится — без предупреждений');

// Скидка: слово на одной строке, сумма на следующей
eq(items('Йогурт 1,50\nСКИДКА\n0,30\nИтого 1,20'), [['Йогурт', 120]], 'сумма скидки строкой ниже');
// Отдельная строка с минусом — тоже скидка
eq(items('Чай 4,20\n-0,70\nИтого 3,50'), [['Чай', 350]], 'строка «-0,70» вычитается из товара выше');
// Название переносится на две строки
eq(items('Шоколад молочный с\nцельным фундуком\n1 x 3,15 3,15\nИтого 3,15'), [['Шоколад молочный с цельным фундуком', 315]], 'длинное название на двух строках');
// Код товара в начале строки убирается, «Картофель» не принимается за «Карта»
eq(items('4810268031234 Картофель молодой 2,40\nИтого 2,40'), [['Картофель молодой', 240]], 'код товара убран, картофель не служебная строка');
// Строка «кол-во x цена = сумма»
eq(items('Вода\n2 x 0,99 = 1,98\nИтого 1,98'), [['Вода', 198]], 'формат «кол-во x цена = сумма»');

// Ничего не распознано
const empty = parseReceipt('какой-то неразборчивый текст\nбез цен');
eq([empty.items.length, empty.warnings.length > 0], [0, true], 'нет товаров — предупреждение');
// Нет строки ИТОГО
eq(parseReceipt('Сок 2,50').warnings[0].includes('ИТОГО'), true, 'нет итога — предупреждение');
// Длинный чек
const long = Array.from({ length: 30 }, (_, i) => `Товар ${i + 1} 1,00`).join('\n') + '\nИтого 30,00';
const lr = parseReceipt(long);
eq([lr.items.length, lr.warnings.some((w) => w.startsWith('Чек длинный'))], [30, true], 'длинный чек — совет внести вручную');

out(`\n${failed ? '✗' : '✓'} Разбор чеков: пройдено ${passed}, упало ${failed}`);
if (typeof globalThis.__testResult === 'function') globalThis.__testResult(passed, failed);
if (failed && typeof process !== 'undefined') process.exitCode = 1;
