// Запуск: jsc -m tests/receipt.test.js  (или node tests/receipt.test.js)
import { parseReceipt } from '../js/lib/receipt-parse.js';

const out = typeof print === 'function' ? print : (...a) => console.log(...a);
let passed = 0;
let failed = 0;

function eq(actual, expected, name) {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) passed++;
  else {
    failed++;
    out(`✗ ${name}\n    ожидали: ${e}\n    получили: ${a}`);
  }
}

const items = (text) => parseReceipt(text).items.map((it) => [it.name, it.amount]);

// Типичный чек: шапка, товары, скидка под товаром, итог, оплата
const receipt = `ООО "Евроторг" УНП 101168731
Магазин №123 г. Минск
Кассир Иванова
Чек № 4567  20.11.2026 12:38
Молоко 3,2% 1л
1 x 2,89   2,89
Скидка        -0,50
Хлеб Нарочанский
1.000 x 1,79   1,79
Бананы
1.234 x 3,49
Картофель 2,10
ИТОГО: 11,59
Карта            11,59
НДС 20%           1,93
Спасибо за покупку!`;
const r = parseReceipt(receipt);
eq(items(receipt), [['Молоко 3,2% 1л', 239], ['Хлеб Нарочанский', 179], ['Бананы', 431], ['Картофель', 210]],
  'чек: товары по строкам, скидка вычтена из товара выше, весовой товар перемножен, служебные строки пропущены');
eq(r.total, 1159, 'итог из строки ИТОГО');
eq(r.warnings.length, 1, 'сумма товаров 10,59 ≠ итог 11,59 — предупреждение');
eq(r.warnings[0].includes('разница 1,00'), true, 'в предупреждении указана разница');

// Итог сходится — предупреждений нет
const ok = `Сыр Гауда 1 x 7,45 7,45
Скидка по карте 0,45
Кефир 1,99
ИТОГО 8,99`;
eq(items(ok), [['Сыр Гауда', 700], ['Кефир', 199]], 'скидка без минуса в той же строке');
eq(parseReceipt(ok).warnings, [], 'итог сходится — без предупреждений');

// Скидка: слово на одной строке, сумма на следующей
eq(items('Йогурт 1,50\nСКИДКА\n0,30\nИтого 1,20'), [['Йогурт', 120]], 'сумма скидки строкой ниже');
// Отдельная строка с минусом — тоже скидка
eq(items('Чай 4,20\n-0,70\nИтого 3,50'), [['Чай', 350]], 'строка «-0,70» вычитается из товара выше');
// Название переносится на две строки
eq(items('Шоколад молочный с\nцельным фундуком\n1 x 3,15 3,15\nИтого 3,15'), [['Шоколад молочный с цельным фундуком', 315]], 'длинное название на двух строках');
// Код товара в начале строки убирается, «Картофель» не принимается за «Карта»
eq(items('4810268031234 Картофель молодой 2,40\nИтого 2,40'), [['Картофель молодой', 240]], 'код товара убран, картофель не служебная строка');
// Строка «кол-во x цена = сумма»
eq(items('Вода\n2 x 0,99 = 1,98\nИтого 1,98'), [['Вода', 198]], 'формат «кол-во x цена = сумма»');

// Ничего не распознано
const empty = parseReceipt('какой-то неразборчивый текст\nбез цен');
eq([empty.items.length, empty.warnings.length > 0], [0, true], 'нет товаров — предупреждение');
// Нет строки ИТОГО
eq(parseReceipt('Сок 2,50').warnings[0].includes('ИТОГО'), true, 'нет итога — предупреждение');
// Длинный чек
const long = Array.from({ length: 30 }, (_, i) => `Товар ${i + 1} 1,00`).join('\n') + '\nИтого 30,00';
const lr = parseReceipt(long);
eq([lr.items.length, lr.warnings.some((w) => w.startsWith('Чек длинный'))], [30, true], 'длинный чек — совет внести вручную');

// ── Настоящий вывод «Живого текста» Apple (VisionKit на Mac, тот же движок, что в Камере iPhone) ──
// Чек копируется по колонкам: сначала названия, «Скидка», «ИТОГО», потом столбик сумм.
const liveText1 = "000 \"Евроторг\"\nУНП 101168731\nМагазин \"Евроопт\" г. Минск\nКАССОВЫЙ ЧЕК Nº 4567\nКассир: Иванова А.\n21.11.2026 09:29\nМолоко \"Савушкин\" 3,2% 1л\n1 шт × 2,89\nСкидка\nХлеб \"Нарочанский\" 0,5кг\n1 шт × 1,79\nБананы вес.\n1,234 кг х 3,49\nКартофель\n1 шт × 2,10\nСыр \"Брест-Литовск\" 200г\n1 шт х 6,45\nСкидка по карте\nИТОГО\nБанковская карта\nВ т.ч. НДС 20%\nСПАСИБО ЗА ПОКУПКУ!\n2,89\n-0,50\n1,79\n4,31\n2,10\n6,45\n-1,20\n15,84\n15,84\n2,64";
eq(items(liveText1), [['Молоко "Савушкин" 3,2% 1л', 239], ['Хлеб "Нарочанский" 0,5кг', 179], ['Бананы вес', 431], ['Картофель', 210], ['Сыр "Брест-Литовск" 200г', 525]],
  'Живой текст: суммы из отдельного столбика встают к своим товарам, скидки вычтены, весовой товар с «кг ×»');
eq([parseReceipt(liveText1).total, parseReceipt(liveText1).warnings], [1584, []], 'Живой текст: итог прочитан из столбика, сходится');

// Фото с наклоном: цена «1, 99» с пробелом, цены в одной строке с названием, перенос названия склеен
const liveText2 = "ЗАО \"Доброном\"\nУНП 190123456\nГипермаркет Гиппо\"\nЧек N 00812\nСмена 15\n21.11.2026 18:04\nКефир 2,5% 900г\nБатон нарезной\nШоколад молочный с цельным фундуком 90г\nСкидка\nЯблоки Голден вес.\n0,856 кг х 2,99\nВода питьевая 1,5л\n2 шт х 0,89\nК ОПЛАТЕ\nНаличные\nСдача\n1, 99\n1,35\n3,15\n-0,40\n2,56\n1,78\n10,43\n20,00\n9,57";
eq(items(liveText2), [['Кефир 2,5% 900г', 199], ['Батон нарезной', 135], ['Шоколад молочный с цельным фундуком 90г', 275], ['Яблоки Голден вес', 256], ['Вода питьевая 1,5л', 178]],
  'Живой текст, фото: «1, 99» склеено, «2,5%» и «1,5л» не цены, скидка вычтена');
eq(parseReceipt(liveText2).total, 1043, 'Живой текст, фото: «К ОПЛАТЕ» как итог');

// Касса печатает «товар 1 x 2,49 =» и сумму справа
const liveText3 = "Кассир 07\nОАО \"Санта Ритейл\"\nУНП 200987654\nКАССОВЫИ ЧЕК N 3301\n21.11.2026 19:12\nТворог 5% 1 х 2,49 =\nСметана 20% 1 х 1,89 =\nСкидка\nОгурцы 0,612 х 4,90 =\nПакет-майка 1 х 0,20 =\nИТОГО К ОПЛАТЕ\n2,49\n1,89\n-0,19\n3,00\n0,20\n7,39";
eq(items(liveText3), [['Творог 5%', 249], ['Сметана 20%', 170], ['Огурцы', 300], ['Пакет-майка', 20]], 'Живой текст: формат «товар 1 x цена =»');
eq(parseReceipt(liveText3).warnings, [], 'Живой текст: «ИТОГО К ОПЛАТЕ» сходится');

// Длинный чек: строки названий и цен перемешаны кусками, одна строка («Сахар 5,69») потерялась при распознавании
const liveText4 = "ООО \"Евроторг\"\nУНП 101168731\nКАССОВЫЙ ЧЕК N 9001\n21.11.2026 20:00\nМолоко\nХлеб\n3,81\nСыр\n2,04\nКефир\n4,54\nЙогурт\n7,16\nМасло\n0,99\nЯйца С1\n1,24\nКолбаса\n8,90\nСосиски\n5,98\n1,46\nГречка\n4,24\nРис\nМакароны\n6,46\n1,09\n5,69\nСоль\nЧай\n2,69\n0,88\nКофе\n1,38\nПеченье\n4,94\nКонфеты\n4,78\nСок\n1,21\nВода\n2,96\nПиво\n1,42\nЧипсы\n6,14\nОрехи\n4,84\nМед\n1, 10\nваренье\n8, 96\nкетчуп\n6,29\nМайонез\n1,76\nГорчица\nМука\n2,78\n6,95\nдрожжи\n6,92\nИтОГО\n119, 60";
const l4 = parseReceipt(liveText4);
eq([l4.items.length, l4.items[0].amount, l4.items[12].name, l4.items[12].amount, l4.items[13].name], [30, 381, 'Без названия', 569, 'Соль'],
  'Живой текст, длинный чек: цены на своих местах, сумма без названия — строкой «Без названия»');
eq([l4.total, l4.items.reduce((s, it) => s + it.amount, 0)], [11960, 11960], 'длинный чек: сумма сходится с итогом');
eq(l4.warnings.length === 1 && l4.warnings[0].startsWith('Чек длинный'), true, 'длинный чек — предупреждение проверить строки');

out(`\n${failed ? '✗' : '✓'} Разбор чеков: пройдено ${passed}, упало ${failed}`);
if (typeof globalThis.__testResult === 'function') globalThis.__testResult(passed, failed);
if (failed && typeof process !== 'undefined') process.exitCode = 1;
