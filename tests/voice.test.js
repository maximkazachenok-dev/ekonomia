// Запуск: jsc -m tests/voice.test.js  (или node tests/voice.test.js)
import { parsePurchase } from '../js/lib/voice-parse.js';

const out = typeof print === 'function' ? print : (...a) => console.log(...a);
let passed = 0;
let failed = 0;

function eq(actual, expected, name) {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) passed++;
  else {
    failed++;
    out(`✗ ${name}\n    ожидали: ${e}\n    получили: ${a}`);
  }
}

const TODAY = '2026-10-15';
const shops = [
  { id: 'gippo', name: 'Гиппо' },
  { id: 'green', name: 'Грин' },
  { id: 'sosedi', name: 'Соседи' },
  { id: 'household', defaultName: 'Бытовая химия и гигиена' },
  { id: 'other', defaultName: 'Другое' },
  { id: 'old', name: 'Евроопт', archived: true },
];
const p = (text) => parsePurchase(text, shops, TODAY);
const it = (name, amount) => ({ name, amount });

// Пример владельца
eq(p('в гиппо купили хлеб 3.5, молоко 2.8'), { shopId: 'gippo', shopGuess: null, date: TODAY, items: [it('Хлеб', 350), it('Молоко', 280)], total: null }, 'пример владельца');
eq(p('В Гиппо купили хлеб 3,5 молоко 2,8').items, [it('Хлеб', 350), it('Молоко', 280)], 'без запятой между товарами, цена через запятую');
eq(p('Грин порошок 8,90 мыло 2').shopId, 'green', 'магазин в начале без предлога');
eq(p('Грин порошок 8,90 мыло 2').items, [it('Порошок', 890), it('Мыло', 200)], 'цена 8,90 и целая 2');

// Падежи и опечатки распознавания
eq(p('вчера у соседей сыр 12,5 и яйца 4').shopId, 'sosedi', 'падеж: у соседей');
eq(p('вчера у соседей сыр 12,5 и яйца 4').date, '2026-10-14', 'вчера');
eq(p('вчера у соседей сыр 12,5 и яйца 4').items, [it('Сыр', 1250), it('Яйца', 400)], '«и» между товарами');
eq(p('позавчера в гипо взяли батон 2').shopId, 'gippo', 'опечатка: гипо');
eq(p('позавчера в гипо взяли батон 2').date, '2026-10-13', 'позавчера');
eq(p('в гиппо батон за 2 рубля 10 копеек').items, [it('Батон', 210)], 'рубли и копейки');
eq(p('гиппо сметана 3 р 5 коп').items, [it('Сметана', 305)], 'сокращения р и коп');

// Числа словами
eq(p('в гиппо кофе за полтора').items, [it('Кофе', 150)], 'полтора');
eq(p('в гиппо хлеб три с половиной').items, [it('Хлеб', 350)], 'три с половиной');
eq(p('в гиппо курица двадцать пять').items, [it('Курица', 2500)], 'двадцать пять');
eq(p('в гиппо хлеб 2 с половиной').items, [it('Хлеб', 250)], '2 с половиной');

// Многословные названия
eq(p('бытовая химия порошок 15 зубная паста 4,2').shopId, 'household', 'раздел из нескольких слов');
eq(p('бытовая химия порошок 15 зубная паста 4,2').items, [it('Порошок', 1500), it('Зубная паста', 420)], 'товар из двух слов');
eq(p('купили в гиппо туалетная бумага 6').items, [it('Туалетная бумага', 600)], 'магазин не в начале');

// Без магазина, неизвестный и скрытый магазин
eq(p('хлеб 3.5').shopId, null, 'без магазина — раздел не угадан');
eq(p('хлеб 3.5').items, [it('Хлеб', 350)], 'без магазина — товары есть');
eq(p('в евроопте хлеб 3').shopId, null, 'скрытый магазин не выбирается');
eq(p('в евроопте хлеб 3').shopGuess, 'Евроопте', 'неизвестный магазин — предложим создать');
eq(p('в евроопте хлеб 3').items, [it('Хлеб', 300)], 'неизвестный магазин — товары есть');
eq(p('в магните молоко 2').shopGuess, 'Магните', 'неизвестный магазин после предлога');

// Особые случаи
eq(p('гиппо 15'), { shopId: 'gippo', shopGuess: null, date: TODAY, items: [], total: 1500 }, 'только общая сумма');
eq(p('в гиппо хлеб 3.5 молоко').items, [it('Хлеб', 350), it('Молоко', 0)], 'товар без цены — цена 0, введут вручную');
eq(p('').items, [], 'пустая фраза');
eq(p('молоко 2.8, мука 1.95 и сахар 3').items.length, 3, 'три товара');
eq(p('Молоко 2.8, мука 1.95 и сахар 3').items[1], it('Мука', 195), 'цена с копейками 1.95');

out(`\n${failed ? '✗' : '✓'} Разбор голоса: пройдено ${passed}, упало ${failed}`);
if (failed && typeof process !== 'undefined') process.exitCode = 1;
